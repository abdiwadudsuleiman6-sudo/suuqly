export async function getDb(): Promise<LowDbInstance> {
  if (dbInstance) return dbInstance;

  fs.mkdirSync(DATA_DIR, { recursive: true });
  ensureSeedAssets(UPLOADS_DIR);

  const defaultData: DatabaseSchema = {
    users: [],
    suppliers: [],
    products: [],
    reviews: [],
    rfqs: [],
    orders: [],
    mpesaTransactions: [],
    complaints: [],
  };

  const db = await JSONFilePreset<DatabaseSchema>(DB_PATH, defaultData);

  if (db.data.users.length === 0 || db.data.products.length === 0) {
    db.data = createSeedData();
    await db.write();
    console.log('[Suuqly DB] Auto-seeded 6+ Garissa suppliers, 24 products, and 4 demo accounts into server/data/db.json');
  }

  dbInstance = db;
  return db;
}
